function applyLang(){
  const base = I18N[currentLang] || I18N.ja;
  const ext = (typeof I18N_EXT !== 'undefined') ? (I18N_EXT[currentLang] || I18N_EXT.ja) : {};
  const T = Object.assign({}, base, ext);

  // Header
  try{ document.querySelector('.hdr-s').textContent = T.appSub; }catch(e){}
  try{ document.getElementById('langLabel').textContent = {ja:'日本語',en:'English',zh:'中文',es:'Español',ko:'한국어'}[currentLang]; }catch(e){}
  try{ document.getElementById('tipBtnLabel').textContent = T.tipBtn; }catch(e){}
  const darkLabel = document.getElementById('darkLabel');
  if(darkLabel) darkLabel.textContent = document.body.classList.contains('dark') ? (T.lightBtn||'ライト') : (T.darkBtn||'ダーク');

  // Tip menu
  try{ document.getElementById('tipMenuTitle').textContent = T.tipMenuTitle; }catch(e){}
  try{ document.getElementById('ofuseBtnTitle').textContent = T.ofuseTitle; }catch(e){}
  try{ document.getElementById('bmcBtnTitle').textContent = T.bmcTitle; }catch(e){}

  // Lang modal
  try{ document.getElementById('langModalTitle').textContent = T.langModalTitle; }catch(e){}

  // AI button - safe update
  const aiBtn = document.getElementById('aiToggleBtn');
  if(aiBtn){
    if(GEMINI_KEY){
      aiBtn.style.background='#E1F5EE'; aiBtn.style.color='#085041'; aiBtn.style.borderColor='#1D9E75';
      aiBtn.innerHTML='<i class="ti ti-sparkles" style="font-size:13px;color:#1D9E75"></i> ' + (T.aiBtn||'AI分析') + ' ON';
    } else {
      aiBtn.style.background='#f3f4f6'; aiBtn.style.color='#6b7280'; aiBtn.style.borderColor='#e5e7eb';
      aiBtn.innerHTML='<i class="ti ti-sparkles" style="font-size:13px"></i> ' + (T.aiBtn||'AI分析');
    }
  }

  // Tabs - safe text node update
  const tabTextKeys = ['analyze','about','vocab','tools'];
  document.querySelectorAll('.tab').forEach((tab, i) => {
    const key = tabTextKeys[i];
    if(!key || !T[key]) return;
    Array.from(tab.childNodes).forEach(node => {
      if(node.nodeType === 3 && node.textContent.trim().length > 0){
        node.textContent = T[key];
      }
    });
  });

  // data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if(T[key]) el.textContent = T[key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if(T[key]) el.placeholder = T[key];
  });

  // Dict toggles
  const xtEn = document.getElementById('xt-en');
  const xtNa = document.getElementById('xt-ja');
  if(xtEn) xtEn.textContent = T.dictEN || 'EN→EN';
  if(xtNa){ xtNa.textContent = T.dictNative || 'EN→JA'; xtNa.style.display = currentLang==='en'?'none':''; }

  // Active lang option
  document.querySelectorAll('.lang-opt').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === currentLang);
  });

  // OFUSE/BMC order
  try{
    const ofuse = document.getElementById('ofuseBtn');
    const bmc = document.getElementById('bmcBtn');
    if(ofuse && bmc){
      const ofuseDesc = document.getElementById('ofuseBtnDesc');
      const bmcDesc = document.getElementById('bmcBtnDesc');
      if(currentLang === 'ja'){
        ofuse.style.order='1'; bmc.style.order='2';
        if(ofuseDesc) ofuseDesc.textContent = T.ofuseDesc||'日本円・PayPay等対応 ← おすすめ';
        if(bmcDesc) bmcDesc.textContent = T.bmcDesc||'クレジットカード・海外向け';
      } else {
        bmc.style.order='1'; ofuse.style.order='2';
        if(bmcDesc) bmcDesc.textContent = (T.bmcDesc||'Credit card') + ' ← Recommended';
        if(ofuseDesc) ofuseDesc.textContent = T.ofuseDesc||'Japanese payment methods';
      }
    }
  }catch(e){}
}


function setLang(lang){
  currentLang = lang;
  localStorage.setItem('ga_lang', lang);
  // Update dict toggle default
  xl = lang === 'en' ? 'en' : lang;
  applyLang();
  closeLangModal();
}

function openLangModal(){
  document.getElementById('langBD').classList.add('show');
  document.getElementById('langSH').classList.add('show');
}
function closeLangModal(){
  document.getElementById('langBD').classList.remove('show');
  document.getElementById('langSH').classList.remove('show');
}
function toggleTipMenu(){
  const m = document.getElementById('tipMenu');
  const bd = document.getElementById('tipMenuBD');
  const show = m.style.display === 'none';
  m.style.display = show ? 'block' : 'none';
  bd.style.display = show ? 'block' : 'none';
}
function closeTipMenu(){
  document.getElementById('tipMenu').style.display = 'none';
  document.getElementById('tipMenuBD').style.display = 'none';
}

